    private void initCustomListeners() {
        // jButton1 = Add Button
        jButton1.addActionListener(e -> addClientAction());

        // jButton2 = Delete Button
        jButton2.addActionListener(e -> deleteClientAction());

        // jComboBox1 = Sort Dropdown ("A-Z" / "Z-A")
        jComboBox1.addActionListener(e -> sortClientAction());
        
        // Table row click listener to auto-fill text fields for easy updating
        jTable1.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting() && jTable1.getSelectedRow() != -1) {
                int row = jTable1.getSelectedRow();
                jTextField1.setText(jTable1.getValueAt(row, 0).toString());
                jTextField2.setText(jTable1.getValueAt(row, 1).toString());
                jTextField3.setText(jTable1.getValueAt(row, 2).toString());
                jTextField4.setText(jTable1.getValueAt(row, 3).toString());
            }
        });
    }
    
    private void addClientAction() {
        String name = jTextField1.getText().trim();
        String email = jTextField2.getText().trim();
        String phone = jTextField3.getText().trim();
        String address = jTextField4.getText().trim();

        if (name.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter at least a Name and Email.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        controller.addClient(name, email, phone, address);
        refreshTable();
        clearFields();
    }
    
    // === INSERT THIS METHOD BELOW addClientAction() ===
    private void updateClientAction() {
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a client from the table to update.", "Selection Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String name = jTextField1.getText().trim();
        String email = jTextField2.getText().trim();
        String phone = jTextField3.getText().trim();
        String address = jTextField4.getText().trim();

        if (name.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Name and Email cannot be empty.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        controller.updateClient(selectedRow, name, email, phone, address);
        refreshTable();
        clearFields();
        jTable1.clearSelection();
    }
    
    private void deleteClientAction() {
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow != -1) {
            controller.removeClient(selectedRow);
            refreshTable();
        } else {
            JOptionPane.showMessageDialog(this, "Please select a client from the table to delete.", "Selection Error", JOptionPane.WARNING_MESSAGE);
        }
    }
    
    private void sortClientAction() {
        boolean ascending = jComboBox1.getSelectedItem().equals("A-Z");
        controller.sortClients(ascending);
        refreshTable();
    }
    
    private void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear current table rows
        for (Client c : controller.getClients()) {
            model.addRow(new Object[]{c.getName(), c.getEmail(), c.getPhone(), c.getAddress()});
        }
    }
    
    private void clearFields() {
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
    }
